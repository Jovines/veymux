  assert.equal(stable.environment.VEYMUX_STABLE_UPDATE_ENDPOINT,stableEndpoint);
  assert.equal(preview.environment.VEYMUX_STABLE_UPDATE_ENDPOINT,stableEndpoint);
  assert.equal(stable.environment.VEYMUX_STABLE_UPDATE_PUBLIC_KEY,preview.environment.VEYMUX_STABLE_UPDATE_PUBLIC_KEY);
  assert.equal(preview.config.identifier,'com.jovines.veymux.preview');
  assert.equal(preview.environment.VEYMUX_DESKTOP_CHANNEL,'preview');
  assert.equal(stable.environment.VEYMUX_DESKTOP_CHANNEL,'stable');
  assert.equal(stable.config.bundle.macOS.infoPlist,'Info.plist');

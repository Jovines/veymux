import { afterEach, expect, it, vi } from 'vitest';
import express from 'express';
import { once } from 'node:events';
import { mkdtempSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { SessionViewModeStore, sessionViewModeRoutes } from './sessionViewModeRoutes';
import { markEncryptedRequest } from '../federation/requestContext';
import { resolveAccessRequest } from '../federation/accessPolicy';
import { detectAgentFromCommand } from './registry';
import { chatProgramName } from '../shared/chatProgramPolicy';
const clean: (() => void)[] = [];
afterEach(() => clean.splice(0).reverse().forEach(fn => fn()));
it('shares a canonical Session preference across clients and reloads, without affecting another Session', async () => {
  const dir = mkdtempSync(join(tmpdir(), 'td-mode-')); clean.push(() => rmSync(dir, { recursive: true, force: true }));
  const path = join(dir, 'modes.json'), store = new SessionViewModeStore(path);
  const app = express(); app.use(express.json()); app.use((req, _res, next) => { markEncryptedRequest(req, String(req.headers['test-device'] || 'first')); next(); });
  const mirror = vi.fn(async () => {});
  app.use(sessionViewModeRoutes(store, id => ['frontend', 'backend'].includes(id) ? 'stable' : undefined, undefined, mirror));
  const server = app.listen(0, '127.0.0.1'); await once(server, 'listening'); clean.push(() => { server.closeAllConnections(); server.close(); });
  const address = server.address(); if (!address || typeof address === 'string') throw new Error(); const base = `http://127.0.0.1:${address.port}`;
  expect((await fetch(`${base}/frontend/view-mode`).then(r => r.json())).mode).toBeNull();
  const save = (mode: string) => fetch(`${base}/frontend/view-mode`, { method: 'PUT', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ mode }) });
  expect((await save('chat')).status).toBe(200);
  expect(mirror).toHaveBeenLastCalledWith('stable', 'chat');
  expect((await fetch(`${base}/backend/view-mode`, { headers: { 'test-device': 'second' } }).then(r => r.json())).mode).toBe('chat');
  expect(new SessionViewModeStore(path).get('stable')?.mode).toBe('chat'); expect(store.get('another')).toBeNull();
  await save('terminal'); expect(new SessionViewModeStore(path).get('stable')?.mode).toBe('terminal');
  expect(mirror).toHaveBeenLastCalledWith('stable', 'terminal');
  expect((await save('invalid')).status).toBe(400); expect((await fetch(`${base}/unknown/view-mode`)).status).toBe(404);
  expect(mirror).toHaveBeenCalledTimes(2);
  expect(resolveAccessRequest('GET', '/api/terminal/frontend/view-mode')).toEqual({ action: 'session.metadata', sessionId: 'frontend' });
  expect(resolveAccessRequest('PUT', '/api/terminal/frontend/view-mode')).toEqual({ action: 'session.view', sessionId: 'frontend' });
});
it('checks live and proposed commands without changing the preference, and keeps the endpoint encrypted', async () => {
  const dir = mkdtempSync(join(tmpdir(), 'td-mode-eligibility-')); clean.push(() => rmSync(dir, { recursive: true, force: true }));
  const store = new SessionViewModeStore(join(dir, 'modes.json'));
  let live = 'cat codex.md';
  const app = express(); app.use((req, _res, next) => { if (req.headers['test-device']) markEncryptedRequest(req, 'owner'); next(); });
  app.use(sessionViewModeRoutes(store, id => id === 'frontend' ? 'stable' : null, (id, command) => {
    expect(id).toBe('stable'); const actual = command ?? live, program = chatProgramName(actual);
    return { allowed: Boolean(detectAgentFromCommand(actual, { cc: 'claude' })) || program === 'my-agent', program };
  }));
  const server = app.listen(0, '127.0.0.1'); await once(server, 'listening'); clean.push(() => { server.closeAllConnections(); server.close(); });
  const address = server.address(); if (!address || typeof address === 'string') throw new Error(); const base = `http://127.0.0.1:${address.port}/frontend/view-mode`;
  const read = (query = '?chatEligibility=1') => fetch(base + query, { headers: { 'test-device': 'owner' } }).then(r => r.json());
  expect((await fetch(base + '?chatEligibility=1')).status).toBe(404);
  expect((await read('')).chatEligibility).toBeUndefined();
  expect((await read()).chatEligibility).toEqual({ allowed: false, program: 'cat' });
  for (const command of ['codex --model test', 'cc', 'my-agent']) expect((await read(`?chatEligibility=1&command=${encodeURIComponent(command)}`)).chatEligibility.allowed).toBe(true);
  expect(store.get('stable')).toBeNull();
  live = 'codex'; expect((await read()).chatEligibility.allowed).toBe(true);
  live = 'zsh'; expect((await read()).chatEligibility).toEqual({ allowed: false, program: null });
});
